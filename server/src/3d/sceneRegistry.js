export function getScenesForIndustry(industry) {
  const norm = (industry || "").toLowerCase();
  const matches = Object.values(SCENE_REGISTRY).filter(s =>
    s.industries.some(i => norm.includes(i.toLowerCase()) || i.toLowerCase().includes(norm))
  );
  if (matches.length > 0) return matches;
  return [SCENE_REGISTRY.FloatingBlobScene, SCENE_REGISTRY.OrbitRingScene, SCENE_REGISTRY.GlassOrbScene];
}

export function getSceneById(id) {
  return SCENE_REGISTRY[id] || SCENE_REGISTRY.FloatingBlobScene;
}
